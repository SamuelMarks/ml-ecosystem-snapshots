"""Function-level test coverage verifier using `.coverage` data and Python AST analysis.

Ensures 100% of runtime-executable functions and methods across `src/` and `scripts/`
have at least one executed body line recorded in `.coverage`.
"""

from __future__ import annotations

import ast
import glob
import os
import sys
from collections.abc import Sequence

import coverage


def _is_overload_or_protocol_stub(
    node: ast.FunctionDef | ast.AsyncFunctionDef,
    in_protocol: bool,
) -> bool:
    """Return whether `node` is a static `@overload` or `Protocol` method stub with no runtime body.

    Args:
        node: Function or async function AST node.
        in_protocol: Whether `node` is defined directly inside a `Protocol` class.

    Returns:
        True if `node` has no executable runtime body statements.
    """
    for dec in node.decorator_list:
        if (isinstance(dec, ast.Name) and dec.id == "overload") or (
            isinstance(dec, ast.Attribute) and dec.attr == "overload"
        ):
            return True

    non_doc_stmts = [
        stmt for stmt in node.body if not (isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant))
    ]
    if not non_doc_stmts:
        return in_protocol
    if in_protocol and len(non_doc_stmts) == 1 and isinstance(non_doc_stmts[0], ast.Pass):
        return True
    return False


def _is_protocol_class(node: ast.ClassDef) -> bool:
    """Return whether `node` inherits from `Protocol` or `<mod>.Protocol`.

    Args:
        node: Class definition AST node.

    Returns:
        True if any base class is `Protocol`.
    """
    return any(
        (isinstance(base, ast.Name) and base.id == "Protocol")
        or (isinstance(base, ast.Attribute) and base.attr == "Protocol")
        for base in node.bases
    )


def _executable_body_lines(node: ast.FunctionDef | ast.AsyncFunctionDef) -> set[int]:
    """Compute executable statement line numbers inside `node`'s own body (excluding docstring & nested defs).

    Args:
        node: Function or async function AST node.

    Returns:
        Set of 1-based line numbers belonging to executable statements of `node`.
    """
    lines: set[int] = set()
    stmts = list(node.body)
    if (
        stmts
        and isinstance(stmts[0], ast.Expr)
        and isinstance(stmts[0].value, ast.Constant)
        and isinstance(stmts[0].value.value, str)
    ):
        stmts = stmts[1:]
    for stmt in stmts:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        lines.add(stmt.lineno)
    return lines


def _collect_functions_in_scope(
    stmts: Sequence[ast.stmt],
    in_protocol: bool,
    in_type_checking: bool,
) -> list[tuple[str, int, set[int]]]:
    """Recursively collect `(qualname, lineno, body_lines)` for runtime functions in `stmts`.

    Args:
        stmts: Sequence of AST statements to walk.
        in_protocol: Whether the current scope is a `Protocol` class body.
        in_type_checking: Whether the current scope is inside `if TYPE_CHECKING:`.

    Returns:
        List of `(name, def_lineno, executable_lines)` tuples.
    """
    if in_type_checking:
        return []
    collected: list[tuple[str, int, set[int]]] = []
    for stmt in stmts:
        if isinstance(stmt, ast.If):
            is_tc = (isinstance(stmt.test, ast.Name) and stmt.test.id == "TYPE_CHECKING") or (
                isinstance(stmt.test, ast.Attribute) and stmt.test.attr == "TYPE_CHECKING"
            )
            collected.extend(_collect_functions_in_scope(stmt.body, in_protocol, is_tc))
            collected.extend(_collect_functions_in_scope(stmt.orelse, in_protocol, False))
        elif isinstance(stmt, ast.ClassDef):
            proto = _is_protocol_class(stmt)
            collected.extend(_collect_functions_in_scope(stmt.body, proto, False))
        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if not _is_overload_or_protocol_stub(stmt, in_protocol):
                body_lines = _executable_body_lines(stmt)
                if body_lines:
                    collected.append((stmt.name, stmt.lineno, body_lines))
            collected.extend(_collect_functions_in_scope(stmt.body, False, False))
    return collected


def check_function_coverage(
    data_file: str = ".coverage",
    roots: Sequence[str] = ("src/ml_ecosystem_snapshots", "scripts"),
) -> list[str]:
    """Verify every runtime function under `roots` has >=1 executed line in `data_file`.

    Args:
        data_file: Path to the SQLite `.coverage` data file generated by `pytest --cov`.
        roots: Sequence of source root directories to inspect.

    Returns:
        List of formatted uncovered-function messages (`filepath:lineno: function '<name>' ...`).

    Raises:
        FileNotFoundError: If `data_file` does not exist on disk.
    """
    if not os.path.exists(data_file):
        raise FileNotFoundError(f"Coverage data file not found: {data_file}")

    cov_data = coverage.CoverageData(basename=data_file)
    cov_data.read()

    measured_map: dict[str, set[int]] = {}
    for measured_path in cov_data.measured_files():
        lines = cov_data.lines(measured_path)
        measured_map[os.path.realpath(measured_path)] = set(lines) if lines is not None else set()

    uncovered: list[str] = []
    for root in roots:
        for filepath in sorted(glob.glob(f"{root}/**/*.py", recursive=True)):
            real_fp = os.path.realpath(filepath)
            executed = measured_map.get(real_fp, set())
            with open(filepath, encoding="utf-8") as handle:
                tree = ast.parse(handle.read(), filename=filepath)
            for fn_name, lineno, body_lines in _collect_functions_in_scope(tree.body, False, False):
                if not (body_lines & executed):
                    uncovered.append(f"{filepath}:{lineno}: uncovered function '{fn_name}'")
    return uncovered


def main(data_file: str = ".coverage") -> int:
    """Run function-level coverage verification and report any unexecuted functions.

    Args:
        data_file: Path to the `.coverage` file to inspect.

    Returns:
        Exit code `0` when 100% of functions are covered, `1` otherwise.
    """
    try:
        uncovered = check_function_coverage(data_file=data_file)
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if uncovered:
        for item in uncovered:
            print(item, file=sys.stderr)
        print(f"Found {len(uncovered)} uncovered function(s).", file=sys.stderr)
        return 1
    print("scripts/check_function_coverage.py: 100.0% function coverage across src/ and scripts/.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
